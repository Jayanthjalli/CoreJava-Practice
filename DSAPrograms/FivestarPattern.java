package com.DSAPrograms;

public class FivestarPattern {
static void fiveStar() {
	for(int i=0;i<5;i++) {
		for(int j=0;j<5;j++) {
		System.out.print("*  ");
		}
		System.out.println();
	}
}
	public static void main(String[] args) {
System.out.println("the 5 star pattern code :");
fiveStar();

	}

}

