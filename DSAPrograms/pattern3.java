public class pattern3 {

	public static void main(String[] args) {
		int row=3;
		int col=20;
for(int i=0;i<row;i++) {
	for(int j=0;j<col;j++) {
		System.out.print("*");
		if(j!=col-1) {
			System.out.print("-");
			
		}
	}		System.out.println();

}
	}

}






